package unidad1;

public class EJ4 {

	public static void main(String[] args) {
		int numero = 5;
        int potenciaDe2 = 3; // Representa 2^3 = 8
        int resultado = numero << potenciaDe2; // Equivale a multiplicar por 2^3 sin usar '*'
        System.out.println("Resultado de multiplicar " + numero + " por 2^" + potenciaDe2 + " es: " + resultado);
	}

}
